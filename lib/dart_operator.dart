/// Dart Operators
void main() {
  ///Arithmetic Operator

  var a = 10;
  var b = 20;
  var c = 30;
  var d = 40;
  print(a + b);
  print(d - c);
  print(d / a);
  print(d * a);

  /// Unary Operator
  var M = 10;

  print(M++); //  postfix
  print(M++); //  postfix
  print(M++); //  postfix
  print(M++); //  postfix
  print(M++); //  postfix

  print(M--); //  postfix
  print(M--); //  postfix
  print(M--); //  postfix
  print(M--); //  postfix
  print(M--); //  postfix

  var L = 10;
  print(++L); //prefix
  print(++L); //prefix
  print(++L); //prefix
  print(++L); //prefix
  print(++L); //prefix

  print(--L); //prefix
  print(--L); //prefix
  print(--L); //prefix
  print(--L); //prefix
  print(--L); //prefix
}
